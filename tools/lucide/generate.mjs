// Writes src/Lampion.App/Controls/Icons/Lucide.cs from the Lucide icons listed in icons.json.
// Usage: node tools/lucide/generate.mjs [path to an unpacked lucide-static package]
// Without a path it downloads the pinned lucide-static version with `npm pack` into a temp folder.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const version = "1.74.0";
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const output = join(root, "src", "Lampion.App", "Controls", "Icons", "Lucide.cs");

function packageDir() {
  if (process.argv[2]) return process.argv[2];
  const temp = mkdtempSync(join(tmpdir(), "lucide-"));
  const shell = process.platform === "win32";
  execFileSync("npm", ["pack", `lucide-static@${version}`, "--silent"], { cwd: temp, shell });
  execFileSync("tar", ["xzf", `lucide-static-${version}.tgz`], { cwd: temp });
  return join(temp, "package");
}

const n = (v) => Number(v);

// Lucide icons are stroked 24×24 outlines made of SVG shapes; Avalonia only parses path data, so every
// shape becomes a sub-path.
function toPath([tag, a]) {
  switch (tag) {
    case "path":
      return absoluteStart(a.d);
    case "line":
      return `M${a.x1} ${a.y1} L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const p = a.points.trim().split(/[\s,]+/);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += ` L${p[i]} ${p[i + 1]}`;
      return tag === "polygon" ? d + " Z" : d;
    }
    case "circle":
    case "ellipse": {
      const [cx, cy] = [n(a.cx), n(a.cy)];
      const [rx, ry] = tag === "circle" ? [n(a.r), n(a.r)] : [n(a.rx), n(a.ry)];
      return `M${cx - rx} ${cy} A${rx} ${ry} 0 1 0 ${cx + rx} ${cy} A${rx} ${ry} 0 1 0 ${cx - rx} ${cy} Z`;
    }
    case "rect": {
      const [x, y, w, h] = [n(a.x ?? 0), n(a.y ?? 0), n(a.width), n(a.height)];
      const rx = Math.min(n(a.rx ?? a.ry ?? 0), w / 2);
      const ry = Math.min(n(a.ry ?? a.rx ?? 0), h / 2);
      if (rx === 0 || ry === 0) return `M${x} ${y} H${x + w} V${y + h} H${x} Z`;
      return (
        `M${x + rx} ${y} H${x + w - rx} A${rx} ${ry} 0 0 1 ${x + w} ${y + ry} V${y + h - ry} ` +
        `A${rx} ${ry} 0 0 1 ${x + w - rx} ${y + h} H${x + rx} A${rx} ${ry} 0 0 1 ${x} ${y + h - ry} ` +
        `V${y + ry} A${rx} ${ry} 0 0 1 ${x + rx} ${y} Z`
      );
    }
    default:
      throw new Error(`Unsupported SVG element <${tag}>`);
  }
}

// The self-closing shapes of icons/<name>.svg as [tag, attributes]; Lucide SVGs contain nothing else.
function shapes(dir, name) {
  let svg;
  try {
    svg = readFileSync(join(dir, "icons", `${name}.svg`), "utf8");
  } catch {
    throw new Error(`lucide-static ${version} has no icon "${name}"`);
  }
  return [...svg.matchAll(/<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*?)\/>/g)].map(([, tag, attrs]) => [
    tag,
    Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v])),
  ]);
}

// A path's leading "m" is absolute on its own but relative once joined after other shapes, so make it "M".
// Pairs following it are relative line-tos, which "M" would turn absolute, so they get an explicit "l".
function absoluteStart(d) {
  const number = String.raw`[-+]?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?`;
  const match = d.match(new RegExp(String.raw`^\s*m\s*(${number})[\s,]*(${number})\s*,?(.*)$`, "s"));
  if (!match) return d;
  const [, x, y, rest] = match;
  return new RegExp(String.raw`^\s*${number}`).test(rest) ? `M${x} ${y} l${rest}` : `M${x} ${y}${rest}`;
}

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

const dir = packageDir();
const names = JSON.parse(readFileSync(join(here, "icons.json"), "utf8"));

const members = names.map((name) => {
  const data = shapes(dir, name).map(toPath).join(" ");
  return `    /// <summary>Lucide "${name}".</summary>\n    public static Geometry ${pascal(name)} { get; } = Geometry.Parse("${data}");`;
});

const source = `// <auto-generated>
// Written by tools/lucide/generate.mjs from lucide-static ${version}. Don't edit by hand: add the icon's name
// to tools/lucide/icons.json and run the script again.
// </auto-generated>
using Avalonia.Media;

namespace Lampion.App.Controls.Icons;

/// <summary>
/// Lucide icons (https://lucide.dev, ISC licence, see LUCIDE-LICENSE.txt) as 24×24 outlines meant to be stroked
/// 2 units wide with round caps and joins. Draw them with <see cref="LucideIcon"/> or <see cref="IconPainter"/>.
/// </summary>
internal static class Lucide
{
${members.join("\n\n")}
}
`;

writeFileSync(output, source);
writeFileSync(join(dirname(output), "LUCIDE-LICENSE.txt"), readFileSync(join(dir, "LICENSE"), "utf8"));
console.log(`Wrote ${names.length} icons to ${output}`);
